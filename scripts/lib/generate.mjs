function buildSeoModule(bundle) {
  const meta = Object.fromEntries(Object.entries(routeMeta(bundle)).map(([route, item]) => [route, {
    ...item,
    titlePL: singleLine(item.titlePL),
    titleEN: singleLine(item.titleEN),
    descriptionPL: singleLine(item.descriptionPL),
    descriptionEN: singleLine(item.descriptionEN)
  }]));
  return `// ${GENERATED_BANNER}\nexport const ORIGIN = ${JSON.stringify(bundle.site.origin)};\nexport type RouteMeta = { titlePL: string; titleEN: string; descriptionPL: string; descriptionEN: string; image?: string; imageAltPL?: string; imageAltEN?: string; year?: string; };\nexport const routeMetadata: Record<string, RouteMeta> = ${escapeScriptJson(meta)};\nexport const canonicalRoutes = Object.keys(routeMetadata);\nexport const projectRoutes = canonicalRoutes.filter(route => route.startsWith(\"/projects/\") && route !== \"/projects/\");\n`;
}

function buildManifest(bundle) {
  const containers = orderedContainers(bundle, { publicOnly: true });
  return {
    schemaVersion: 1,
    generatedAt: "deterministic",
    routes: [
      { name: "home", route: "/", file: "index.html" },
      { name: "portfolio", route: "/portfolio/", file: "portfolio/index.html" },
      { name: "projects", route: "/projects/", file: "projects/index.html" },
      ...containers.map(record => ({ name: record.id, route: `/projects/${record.id}/`, file: `projects/${record.id}/index.html`, recordType: record.recordType }))
    ]
  };
}

function buildSitemap(bundle) {
  const routes = buildManifest(bundle).routes;
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${routes.map(({ route }) => `  <url><loc>${escapeHtml(bundle.site.origin)}${route}</loc></url>`).join("\n")}\n</urlset>\n`;
}

async function existing(file) {
  try { return await readFile(file, "utf8"); } catch (error) { if (error.code === "ENOENT") return null; throw error; }
}

async function atomicWrite(file, content) {
  await mkdir(path.dirname(file), { recursive: true });
  if (await existing(file) === content) return false;
  const temp = `${file}.${process.pid}.tmp`;
  await writeFile(temp, content, "utf8");
  await rename(temp, file);
  return true;
}

export async function generateSite(bundle, { root = PROJECT_ROOT, check = false, preview = false } = {}) {
  const validation = await validateContent(bundle, { root, checkFiles: true, publish: false });
  if (!validation.valid) {
    const error = new Error(`Content validation failed with ${validation.errors.length} error(s).`);
    error.validation = validation;
    throw error;
  }
  const runtime = compileRuntimeData(bundle);
  const manifest = buildManifest(bundle);
  const outputs = new Map([
    ["assets/js/data.js", `// ${GENERATED_BANNER}\nwindow.PORTFOLIO_DATA = ${escapeScriptJson(runtime)};\n`],
    ["assets/js/site-data.js", `// ${GENERATED_BANNER}\nwindow.PORTFOLIO_SITE = ${escapeScriptJson(bundle.site)};\n`],
    ["seo-metadata.ts", buildSeoModule(bundle)],
    ["generated/site-manifest.json", `${JSON.stringify(manifest, null, 2)}\n`],
    ["public/sitemap.xml", buildSitemap(bundle)],
    ["index.html", renderHome(bundle)],
    ["portfolio/index.html", renderPortfolio(bundle)],
    ["projects/index.html", renderProjects(bundle)]
  ]);
  for (const record of orderedContainers(bundle, { publicOnly: true })) outputs.set(`projects/${record.id}/index.html`, renderProject(record));
  if (preview && !check) {
    const previewRuntime = compileRuntimeData(bundle, { includeDrafts: true });
    outputs.set("studio-preview/data.js", `// Local draft preview; never publish.\nwindow.PORTFOLIO_DATA = ${escapeScriptJson(previewRuntime)};\n`);
    outputs.set("studio-preview/portfolio/index.html", previewDocument(renderPortfolio(bundle), "index"));
    outputs.set("studio-preview/projects/index.html", previewDocument(renderProjects(bundle), "index"));
    for (const record of orderedContainers(bundle)) outputs.set(`studio-preview/projects/${record.id}/index.html`, previewDocument(renderProject(record), "project"));
  }

  const drift = [];
  let changed = 0;
  for (const [relative, content] of outputs) {
    const file = path.resolve(root, relative);
    const previous = await existing(file);
    if (previous !== content) drift.push(relative);
    if (!check && previous !== content && await atomicWrite(file, content)) changed += 1;
  }
  if (check && drift.length) {
    const error = new Error(`Generated outputs are stale: ${drift.join(", ")}`);
    error.drift = drift;
    throw error;
  }
  return { changed, drift, manifest, validation };
}

export async function removeOwnedRoute(file, { root = PROJECT_ROOT } = {}) {
  const absolute = path.resolve(root, file);
  if (!absolute.startsWith(`${path.resolve(root)}${path.sep}`)) throw new Error("Owned route escaped the repository.");
  const source = await existing(absolute);
  if (source && source.includes(GENERATED_BANNER)) await rm(absolute, { force: true });
}
