const GENERATED_BANNER = "Generated by Portfolio Studio. Edit content/*.json, not this file.";

const escapeHtml = value => String(value ?? "").replace(/[&<>"']/g, character => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
})[character]);
const singleLine = value => String(value ?? "").replace(/\s+/gu, " ").trim();
const escapeAttribute = value => escapeHtml(value).replace(/\r\n?|\n/g, "&#10;");

const escapeScriptJson = value => JSON.stringify(value, null, 2)
  .replace(/</g, "\\u003c")
  .replace(/\u2028/g, "\\u2028")
  .replace(/\u2029/g, "\\u2029");

function compileMedia(media) {
  if (!media || typeof media !== "object") return media;
  const output = structuredClone(media);
  if (output.kind === "group") output.items = (output.items || []).map(compileMedia);
  if (output.focalPoint && Number.isFinite(output.focalPoint.x) && Number.isFinite(output.focalPoint.y)) {
    output.objectPosition = `${Math.round(output.focalPoint.x * 10000) / 100}% ${Math.round(output.focalPoint.y * 10000) / 100}%`;
  }
  delete output.focalPoint;
  delete output.transparencyMode;
  return output;
}

function compileRuntimeRecord(record) {
  const output = runtimeRecord(record);
  for (const key of ["cover", "hero", "thumbnail"]) if (output[key]) output[key] = compileMedia(output[key]);
  if (Array.isArray(output.gallery)) output.gallery = output.gallery.map(compileMedia);
  if (output.video?.poster) output.video.poster = compileMedia(output.video.poster);
  return output;
}

function orderedContainers(bundle, { publicOnly = false } = {}) {
  return [...bundle.projects, ...bundle.collections]
    .filter(record => !publicOnly || (record.published === true && record.draft !== true))
    .sort((a, b) => Number(a.order) - Number(b.order) || a.id.localeCompare(b.id));
}

export function compileRuntimeData(bundle, { includeDrafts = false } = {}) {
  const compile = record => {
    const output = compileRuntimeRecord(record);
    if (includeDrafts) output.draft = false;
    return output;
  };
  const containers = orderedContainers(bundle, { publicOnly: !includeDrafts }).map(compile);
  const collectionIds = bundle.collections
    .filter(record => includeDrafts || (record.published === true && record.draft !== true))
    .sort((a, b) => Number(a.order) - Number(b.order) || a.id.localeCompare(b.id))
    .map(record => record.id);
  const publicWorks = bundle.works
    .filter(record => !record.detailOnly && (includeDrafts || (record.published === true && record.draft !== true)))
    .sort((a, b) => Number(a.order) - Number(b.order) || a.id.localeCompare(b.id))
    .map(compile);
  const detailMedia = bundle.works
    .filter(record => record.detailOnly && (includeDrafts || (record.published === true && record.draft !== true)))
    .sort((a, b) => Number(a.order) - Number(b.order) || a.id.localeCompare(b.id))
    .map(compile);
  return { projects: containers, collectionIds, works: publicWorks, detailMedia };
}

function previewDocument(html, kind) {
  const project = kind === "project";
  const oldAssets = project ? "../../assets/" : "../assets/";
  const newAssets = project ? "../../../assets/" : "../../assets/";
  const dataSource = project ? "../../data.js" : "../data.js";
  const oldBase = project ? 'data-base="../.."' : 'data-base=".."';
  const newBase = project ? 'data-base="../../.."' : 'data-base="../.."';
  return html
    .replaceAll(oldAssets, newAssets)
    .replace(`${newAssets}js/data.js`, dataSource)
    .replace(oldBase, newBase);
}

function routeMeta(bundle) {
  const site = bundle.site;
  const output = {
    "/": site.pages.home,
    "/portfolio/": site.pages.portfolio,
    "/projects/": site.pages.projects
  };
  for (const record of orderedContainers(bundle, { publicOnly: true })) {
    output[`/projects/${record.id}/`] = {
      ...record.seo,
      year: record.yearEN || record.yearPL || undefined
    };
  }
  return output;
}

